IF OBJECT_ID('dbo.CATEGORIA', 'U') IS NULL
CREATE TABLE dbo.CATEGORIA
(
    ID_CATEGORIA INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_CATEGORIA PRIMARY KEY,
    DESCRIPCION  NVARCHAR(50)  NOT NULL CONSTRAINT UQ_CATEGORIA_DESCRIPCION UNIQUE,
    CUOTA_BASE   DECIMAL(10,2) NOT NULL CONSTRAINT CK_CATEGORIA_CUOTA CHECK (CUOTA_BASE >= 0)
);
GO

IF OBJECT_ID('dbo.SOCIO', 'U') IS NULL
CREATE TABLE dbo.SOCIO
(
    ID_SOCIO     INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SOCIO PRIMARY KEY,
    NOMBRE       NVARCHAR(50)  NOT NULL,
    APELLIDO     NVARCHAR(50)  NOT NULL,
    DNI          NVARCHAR(8)   NOT NULL CONSTRAINT UQ_SOCIO_DNI UNIQUE,
    EMAIL        NVARCHAR(100) NOT NULL,
    TELEFONO     NVARCHAR(20)  NULL,
    FECHA_ALTA   DATETIME      NOT NULL CONSTRAINT DF_SOCIO_FECHA_ALTA DEFAULT GETDATE(),
    ACTIVO       BIT           NOT NULL CONSTRAINT DF_SOCIO_ACTIVO DEFAULT 1,
    ID_CATEGORIA INT           NOT NULL CONSTRAINT FK_SOCIO_CATEGORIA REFERENCES dbo.CATEGORIA (ID_CATEGORIA)
);
GO

IF OBJECT_ID('dbo.ACTIVIDAD', 'U') IS NULL
CREATE TABLE dbo.ACTIVIDAD
(
    ID_ACTIVIDAD INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ACTIVIDAD PRIMARY KEY,
    NOMBRE       NVARCHAR(80)  NOT NULL CONSTRAINT UQ_ACTIVIDAD_NOMBRE UNIQUE,
    ARANCEL      DECIMAL(10,2) NOT NULL CONSTRAINT CK_ACTIVIDAD_ARANCEL CHECK (ARANCEL >= 0),
    CUPO         INT           NOT NULL CONSTRAINT CK_ACTIVIDAD_CUPO CHECK (CUPO > 0)
);
GO

IF OBJECT_ID('dbo.INSCRIPCION', 'U') IS NULL
CREATE TABLE dbo.INSCRIPCION
(
    ID_SOCIO          INT           NOT NULL CONSTRAINT FK_INSCRIPCION_SOCIO REFERENCES dbo.SOCIO (ID_SOCIO),
    ID_ACTIVIDAD      INT           NOT NULL CONSTRAINT FK_INSCRIPCION_ACTIVIDAD REFERENCES dbo.ACTIVIDAD (ID_ACTIVIDAD),
    FECHA_INSCRIPCION DATETIME      NOT NULL CONSTRAINT DF_INSCRIPCION_FECHA DEFAULT GETDATE(),
    ARANCEL_APLICADO  DECIMAL(10,2) NOT NULL,
    CONSTRAINT PK_INSCRIPCION PRIMARY KEY (ID_SOCIO, ID_ACTIVIDAD)
);
GO

